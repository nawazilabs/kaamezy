"""Trains the small advisory risk model and writes config/risk_model.yaml. Pure Python, seeded: same run, same file.

HONESTY: there is no real claims data in this prototype. The training set is SYNTHETIC: a generator we wrote draws ordinary
claims and claims with the unusual patterns an insurer's reviewer looks at (very early, close to the cover, very high cost
per day, a round total, an approval far above the estimate). The model therefore learns OUR idea of "unusual", not fraud:
it is advisory, explainable (per-feature contributions), and only ever asks a person to look.

Run: python -m data.train_risk_model          (tests/test_risk.py fails if the committed file is stale)
"""
from __future__ import annotations

import math
import random
from pathlib import Path

import yaml

OUT = Path(__file__).resolve().parent.parent / "config" / "risk_model.yaml"
FEATURES = ["ln_bill", "stay_days", "ln_cost_per_day", "bill_over_cover", "ln_policy_age_days", "approved_over_claimed",
            "round_total", "approved_over_estimate"]
SEED, N, EPOCHS, LR, L2 = 7, 6000, 400, 0.3, 0.001
FLAG_AT = 0.90      # keep equal to config/risk.yaml ml.flag_at (tests/test_risk.py checks)


def one(rng: random.Random, bad: bool) -> tuple[list[float], int]:
    cover = rng.choice([300000, 500000, 1000000])
    stay = rng.choice([1, 2, 2, 3, 3, 4, 5, 6, 8, 10])
    per_day = math.exp(rng.gauss(math.log(22000), 0.45))
    age = rng.randint(60, 1600)
    ratio = min(1.0, max(0.5, rng.gauss(0.85, 0.1)))
    est = max(0.5, rng.gauss(1.0, 0.07))
    bill = per_day * stay
    if bad:
        for pattern in rng.sample(range(6), rng.choice([1, 1, 2])):
            if pattern == 0:
                age = rng.randint(1, 40)
            elif pattern == 1:
                bill = cover * rng.uniform(0.9, 1.2)
            elif pattern == 2:
                per_day = rng.uniform(65000, 140000)
                bill = per_day * stay
            elif pattern == 3:
                stay = 1
                bill = rng.uniform(150000, 400000)
            elif pattern == 4:
                bill = float(rng.choice([60000, 100000, 150000, 200000, 250000, 300000]))
            else:
                est = rng.uniform(1.25, 2.2)
                ratio = 1.0
    elif rng.random() < 0.10:      # honest bills are sometimes round too: a round total alone must not give a claim away
        bill = round(bill / 10000) * 10000
    bill = max(5000.0, bill)
    round_total = 1.0 if bill >= 50000 and int(bill) % 10000 == 0 else 0.0
    x = [math.log(bill), float(stay), math.log(bill / stay), min(bill / cover, 1.5), math.log(1 + age), ratio, round_total, min(est, 3.0)]
    return x, int(bad)


def sigmoid(z: float) -> float:
    return 1 / (1 + math.exp(-max(min(z, 30), -30)))


def auc(scores: list[float], labels: list[int]) -> float:
    pos = [s for s, y in zip(scores, labels) if y]
    neg = [s for s, y in zip(scores, labels) if not y]
    wins = sum((p > n) + 0.5 * (p == n) for p in pos for n in neg)
    return wins / (len(pos) * len(neg))


def train() -> dict:
    rng = random.Random(SEED)
    data = [one(rng, rng.random() < 0.18) for _ in range(N)]
    split = int(N * 0.8)
    tr, te = data[:split], data[split:]
    mean = [sum(r[0][j] for r in tr) / len(tr) for j in range(len(FEATURES))]
    std = [max(math.sqrt(sum((r[0][j] - mean[j]) ** 2 for r in tr) / len(tr)), 1e-9) for j in range(len(FEATURES))]
    z = lambda x: [(x[j] - mean[j]) / std[j] for j in range(len(x))]   # noqa: E731
    Xtr, ytr = [z(r[0]) for r in tr], [r[1] for r in tr]
    w, b = [0.0] * len(FEATURES), 0.0
    for _ in range(EPOCHS):
        gw, gb = [0.0] * len(w), 0.0
        for x, y in zip(Xtr, ytr):
            e = sigmoid(sum(wi * xi for wi, xi in zip(w, x)) + b) - y
            gb += e
            for j, xj in enumerate(x):
                gw[j] += e * xj
        n = len(Xtr)
        w = [wi - LR * (g / n + L2 * wi) for wi, g in zip(w, gw)]
        b -= LR * gb / n
    scores = [sigmoid(sum(wi * xi for wi, xi in zip(w, z(r[0]))) + b) for r in te]
    labels = [r[1] for r in te]
    flagged = [s >= FLAG_AT for s in scores]
    tp = sum(f and y for f, y in zip(flagged, labels))
    return {"note": "GENERATED by data/train_risk_model.py on SYNTHETIC claims. Advisory only: it learns our own idea of 'unusual', not fraud. Do not edit by hand.",
            "trained_on": {"kind": "synthetic", "seed": SEED, "claims": N, "unusual_share_pct": 18},
            "held_out": {"flag_at": FLAG_AT, "claims": len(te), "auc": round(auc(scores, labels), 3),
                         "recall_at_flag": round(tp / max(sum(labels), 1), 3), "precision_at_flag": round(tp / max(sum(flagged), 1), 3)},
            "features": FEATURES, "mean": [round(m, 6) for m in mean], "std": [round(s, 6) for s in std],
            "weights": [round(x, 6) for x in w], "bias": round(b, 6)}


if __name__ == "__main__":
    model = train()
    OUT.write_text(yaml.safe_dump(model, sort_keys=False, allow_unicode=True), encoding="utf-8")
    print("wrote", OUT, "held-out", model["held_out"])
